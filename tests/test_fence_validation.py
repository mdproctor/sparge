        page.wait_for_selector('.pi', timeout=10000)

        page.locator('.filter-always button').filter(has_text='MD⚠').click()
        page.wait_for_timeout(200)
        self._open_md_breakdown(page)

        count_el = page.locator('#md-breakdown .itr[data-key="unbalanced_fences"] .itr-count')
        count_el.wait_for(state='visible', timeout=3000)
        count = int(count_el.inner_text())
