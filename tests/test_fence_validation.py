"""
Integration test: broken fences detected by validate-md and surfaced in UI breakdown.

The real-world bug (discovered on KIE post 2013-10-31-configuration-and-convention...):
  Old convert_post.py + html2text produces this for DocBook <div class="example"> blocks:

      [**Example 2.34. kmodule.xml** ```xml
      <kmodule/>
      ```](<http://blog.athico.com/>)[](<http://blog.athico.com/>)

  The closing line is ```](<url>)  — backticks followed by a Markdown link.
  This is NOT a valid CommonMark closing fence (closing fences must have ONLY backticks).

  The original chk_balanced_fences used a naive check (run >= in_fence) that
  treated ```](<url>) as a valid closer.  With multiple DocBook examples, the
  ```](<url>) lines alternately open and close fences, ending with in_fence=0 —
  so the validator reported NO unbalanced_fences even though the page rendered
  entirely as one giant code block.

  The fix: require re.fullmatch(r'`+\\s*', line) for a valid closing fence.
  A line with ```](<url>) after the backticks fails fullmatch and is kept as content.

This test proves the full pipeline:
  1. Broken MD on disk  (simulating old-code-generated content with real URL pattern)
  2. POST /api/posts/{slug}/validate-md  →  md.issues populated in state.json
  3. UI MD⚠ filter + breakdown  →  unbalanced_fences appears

NOTE: the Sparge server must be restarted after patching md_validator.py for the
API tests to pick up the new chk_balanced_fences logic (Python imports are cached
at server startup).

Run with server on localhost:9000:
  python3 -m pytest tests/test_fence_validation.py -v

Playwright required: playwright install chromium
"""
